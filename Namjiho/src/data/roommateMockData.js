// matching algorithm
export function calculateMatchPercentage(myAnswers, targetAnswers) {
  let score = 0;
  let totalItems = 0;

  // 1. Gender check (Must be equal for dorm assignment - 100% blocker in real life, but here we filter first or just check)
  if (myAnswers.gender && targetAnswers.gender) {
    if (myAnswers.gender !== targetAnswers.gender) return 0;
  }

  // Define attributes & weights
  const questions = [
    { key: "smoking", weight: 3 }, // Smoking is highly sensitive
    { key: "sleepHabit", weight: 3 }, // sleepHabit (snoring, etc.) is highly sensitive
    { key: "soundSensitivity", weight: 2 },
    { key: "alarmSensitivity", weight: 2 },
    { key: "nightActivity", weight: 2 },
    { key: "cleaning", weight: 2 },
    { key: "indoorEating", weight: 2 },
    { key: "showerTime", weight: 1 },
    { key: "homeFreq", weight: 1 },
    { key: "hotSensitivity", weight: 1 },
    { key: "coldSensitivity", weight: 1 },
    { key: "scentSensitivity", weight: 1 }
  ];

  questions.forEach(q => {
    const myVal = myAnswers[q.key];
    const tarVal = targetAnswers[q.key];

    if (myVal !== undefined && tarVal !== undefined) {
      totalItems += q.weight;
      if (myVal === tarVal) {
        score += q.weight;
      } else {
        // Partial matches for ordinal scales or categories
        if (q.key === "sleepHabit") {
          // If neither has sleepHabit, it's a match.
          // If one has '잠꼬대' or '이갈이', it's partially okay. '코골이' is worst.
          if (myVal === "없음" && tarVal === "없음") {
            score += q.weight;
          } else if (myVal !== "코골이" && tarVal !== "코골이") {
            score += q.weight * 0.5; // partial match
          }
        } else if (["soundSensitivity", "alarmSensitivity", "cleaning", "hotSensitivity", "coldSensitivity"].includes(q.key)) {
          // If they differ by 1 step (e.g. '밝음' vs '중간'), they get partial points
          const scale = ["밝음", "어두움", "많이 탐", "적게 탐", "자주", "한 번에", "잘 들음", "못 들음", "중간"];
          // We can just give 0.5 points for closeness
          if ((myVal === "중간" || tarVal === "중간")) {
            score += q.weight * 0.5;
          }
        }
      }
    }
  });

  if (totalItems === 0) return 70; // default base match
  const percentage = Math.round((score / totalItems) * 100);
  return Math.max(30, Math.min(percentage, 100)); // cap between 30% and 100%
}
